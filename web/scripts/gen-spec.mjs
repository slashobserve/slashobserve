import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import Ajv2020 from "ajv/dist/2020.js"
import standaloneCode from "ajv/dist/standalone/index.js"
import { compile } from "json-schema-to-typescript"

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const schemaPath = path.resolve(webDir, "../spec/schema/observespec.v0.json")
const defaultsPath = path.resolve(webDir, "../spec/schema/defaults.json")
const outDir = path.join(webDir, "src/spec")
const bannerFor = (source) =>
  `/* Generated by web/scripts/gen-spec.mjs from ${source}. Do not edit; run make generate. */`
const banner = bannerFor("spec/schema/observespec.v0.json")

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"))
const defaults = JSON.parse(fs.readFileSync(defaultsPath, "utf8"))

const types = await compile(schema, "Dashboard", {
  bannerComment: banner,
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
})

const ajv = new Ajv2020({
  code: { source: true, esm: true },
  allErrors: true,
  strict: true,
  discriminator: true,
})
ajv.addKeyword({ keyword: "x-omitFromPrompt", schemaType: "boolean" })
ajv.addSchema(schema)
let code = standaloneCode(ajv, {
  validate: schema.$id,
  dataPanel: `${schema.$id}#/$defs/dataPanel`,
  textPanel: `${schema.$id}#/$defs/textPanel`,
  placeholderPanel: `${schema.$id}#/$defs/placeholderPanel`,
  dashlistPanel: `${schema.$id}#/$defs/dashlistPanel`,
  newsPanel: `${schema.$id}#/$defs/newsPanel`,
  rowPanel: `${schema.$id}#/$defs/rowPanel`,
  panelQuery: `${schema.$id}#/$defs/panelQuery`,
  expressionQuery: `${schema.$id}#/$defs/expressionQuery`,
  dashboardQuery: `${schema.$id}#/$defs/dashboardQuery`,
})
code = code.replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  "const $1 = (s) => Array.from(s).length;"
)
code = code.replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/g,
  (_, name) => `const ${name} = (a, b) => {
  if (a === b) return true
  if (typeof a !== "object" || typeof b !== "object" || a === null || b === null) return false
  if (Array.isArray(a) !== Array.isArray(b)) return false
  if (Array.isArray(a)) return a.length === b.length && a.every((v, i) => ${name}(v, b[i]))
  const ka = Object.keys(a)
  return ka.length === Object.keys(b).length && ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && ${name}(a[k], b[k]))
};`
)
if (
  /\brequire\(|\bimport\s*\(|^\s*import\s|^\s*export\s[^\n]*\sfrom\s/m.test(
    code
  )
) {
  throw new Error(
    "standalone validator still imports a runtime module; extend the inlining in gen-spec.mjs"
  )
}
const validator = `${banner}\n// @ts-nocheck\n${code}\n`

const defaultsModule = `${bannerFor("spec/schema/defaults.json")}\nexport const specDefaults = ${JSON.stringify(defaults, null, 2)} as const\n`

const displayKeysByType = Object.fromEntries([
  ...schema.$defs.dataPanel.allOf.flatMap((rule) =>
    rule.if?.properties?.type?.const && rule.then?.properties?.display
      ? [
          [
            rule.if.properties.type.const,
            Object.keys(rule.then.properties.display.properties),
          ],
        ]
      : []
  ),
  [
    "dashlist",
    Object.keys(schema.$defs.dashlistPanel.properties.display.properties),
  ],
  ["news", Object.keys(schema.$defs.newsPanel.properties.display.properties)],
])
const displayKeyUnion = [...new Set(Object.values(displayKeysByType).flat())]
  .sort()
  .map((key) => `  | ${JSON.stringify(key)}`)
  .join("\n")
const displayKeysModule = `${banner}\nexport type DisplayKey =\n${displayKeyUnion}\n\nexport const displayKeysByType: Record<string, readonly string[]> = ${JSON.stringify(displayKeysByType, null, 2)}\n`

const refKinds = {
  "#/$defs/color": { kind: "color", pattern: schema.$defs.color.pattern },
  "#/$defs/unit": { kind: "unit" },
  "#/$defs/thresholds": { kind: "thresholds" },
}

function optionSchema(property) {
  if (property.$ref in refKinds) return refKinds[property.$ref]
  const resolved = property.$ref
    ? schema.$defs[property.$ref.replace("#/$defs/", "")]
    : property
  if (resolved.enum) return { kind: "enum", values: resolved.enum }
  if (resolved.type === "boolean") return { kind: "toggle" }
  if (resolved.type === "integer" || resolved.type === "number") {
    return {
      kind: "number",
      integer: resolved.type === "integer",
      ...(resolved.minimum === undefined ? {} : { min: resolved.minimum }),
      ...(resolved.maximum === undefined ? {} : { max: resolved.maximum }),
      ...(resolved.exclusiveMinimum === undefined
        ? {}
        : { min: resolved.exclusiveMinimum, minExclusive: true }),
    }
  }
  if (resolved.type === "string") {
    return {
      kind: "text",
      ...(resolved.maxLength === undefined
        ? {}
        : { maxLength: resolved.maxLength }),
      ...(resolved.pattern === undefined ? {} : { pattern: resolved.pattern }),
    }
  }
  return { kind: "json" }
}

function optionSchemas(properties, keys) {
  return Object.fromEntries(
    keys.map((key) => {
      const property = properties[key]
      const description =
        property.description ??
        (property.$ref
          ? schema.$defs[property.$ref.replace("#/$defs/", "")].description
          : undefined)
      return [
        key,
        {
          ...optionSchema(property),
          ...(description ? { description } : {}),
        },
      ]
    })
  )
}

const panelOptionKeys = [
  "description",
  "timeFrom",
  "timeShift",
  "hideTimeOverride",
  "interval",
  "maxDataPoints",
  "transparent",
  "titleHidden",
  "timezone",
  "repeat",
  "repeatDirection",
  "maxPerRow",
]
const fieldProps = schema.$defs.fieldProps.properties
const fieldOptionsModule = `${banner}
export const fieldOptionSchemas = ${JSON.stringify(optionSchemas(fieldProps, Object.keys(fieldProps)), null, 2)} as const

export const panelOptionSchemas = ${JSON.stringify(optionSchemas(schema.$defs.dataPanel.properties, panelOptionKeys), null, 2)} as const
`

const outputs = {
  "observespec.gen.ts": types,
  "field-options.gen.ts": fieldOptionsModule,
  "validate.gen.ts": validator,
  "defaults.gen.ts": defaultsModule,
  "display-keys.gen.ts": displayKeysModule,
}
const check = process.argv.includes("--check")
const stale = []
if (check && fs.existsSync(outDir)) {
  for (const name of fs.readdirSync(outDir)) {
    if (name.endsWith(".gen.ts") && !(name in outputs)) stale.push(name)
  }
}
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(outDir, name)
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
      stale.push(name)
    }
  } else {
    fs.mkdirSync(outDir, { recursive: true })
    fs.writeFileSync(file, content)
  }
}
if (stale.length > 0) {
  console.error(
    `web/src/spec is stale (${stale.join(", ")}); run make generate`
  )
  process.exit(1)
}
